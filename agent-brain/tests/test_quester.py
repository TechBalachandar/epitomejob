AUTH = {"Authorization": "Bearer test-token"}
KNOWN = ["/jobs", "/resumes/{resumeId}", "/profiles/me"]


class FakeQuesterLLM:
    """Canned LLM replies, in order; records every call."""

    def __init__(self, replies: list[str | None]) -> None:
        self.replies = list(replies)
        self.calls: list[tuple[list[dict[str, str]], float | None]] = []

    async def chat(
        self, messages: list[dict[str, str]], temperature: float | None = None
    ) -> str | None:
        self.calls.append((messages, temperature))
        if self.replies:
            return self.replies.pop(0)
        return None


def _client() -> TestClient:
    return TestClient(app, raise_server_exceptions=False)


async def _fake_validate(token: str, java_base_url: str, client=None):  # type: ignore[no-untyped-def]
    return {"userId": USER_ID, "headline": "Java Developer"}


def _patch_auth_and_llm(monkeypatch, llm):  # type: ignore[no-untyped-def]
    monkeypatch.setattr(quester_router, "validate_token", _fake_validate)
    monkeypatch.setattr(quester_router, "get_llm", lambda: llm)



def test_validate_typescript_structural() -> None:
    good = 'import { test } from "@playwright/test";\ntest("x", async () => {});\n'
    problems, notes = v.validate_generated("web/e2e/a.spec.ts", good)
    assert problems == []
    assert any("structural check only" in n for n in notes)
    problems, _ = v.validate_generated("web/e2e/a.spec.ts", "test(\"x\", async () => {\n")
    assert problems  # unbalanced brace


def test_endpoint_extraction_and_template_matching() -> None:
    content = (
        'import httpx\n'
        'httpx.get(f"{BASE_URL}/jobs")\n'
        'httpx.get("http://localhost:8080/resumes/abc-123")\n'
        'page.goto("/dashboard")\n'  # navigation, not an API call: not extracted
    )
    refs = v.extract_referenced_endpoints(content)
    assert refs == {"/jobs", "/resumes/abc-123"}
    assert v.endpoint_allowed("/resumes/abc-123", ["/resumes/{resumeId}"])
    assert not v.endpoint_allowed("/resumes/abc-123", ["/jobs"])
    assert v.unknown_endpoints(content, KNOWN) == set()
    assert v.unknown_endpoints(content, ["/jobs"]) == {"/resumes/abc-123"}
    # Without a known list the guard cannot run — it returns nothing.
    assert v.unknown_endpoints(content, []) == set()



# -- analyze-failure: deterministic signatures -------------------------------

TRIAGE_CASES = [
    (
        "port-conflict",
        "FAILED tests/test_x.py::test_y\n"
        "Error response from daemon: driver failed programming external connectivity: "
        "Bind for 0.0.0.0:9000 failed: port is already allocated",
        "environment",
        "port-conflict",
        "lsof",
    ),
    (
        "testcontainers-api-version",
        "GateJourneyIT: java.lang.IllegalStateException: Testcontainers version "
        "1.21.3 is not compatible with Docker Engine API version 29: client version too old",
        "environment",
        "testcontainers-api-version",
        "Testcontainers version",
    ),
    (
        "ollama-down",
        "httpx.ConnectError: [Errno 111] Connection refused (localhost:11434) "
        "while calling Ollama /api/chat",
        "environment",
        "ollama-down",
        "ollama serve",
    ),
    (
        "retry-passed-flaky",
        "test_login failed on the first run, then passed on retry with no code change — flaky?",
        "flaky",
        "retry-passed",
        "quarantine",
    ),
    (
        "assertion-failure",
        "FAILED tests/test_matching.py::test_score\n"
        "AssertionError: assert 0.42 == 0.82\n  +  where 0.42 = match['score']",
        "regression",
        "assertion-failure",
        "most recent commit",
    ),
]


@pytest.mark.parametrize(
    "case_id,failure_text,verdict,sig,do_first_snippet", TRIAGE_CASES,
    ids=[c[0] for c in TRIAGE_CASES],
)
async def test_analyze_failure_deterministic_signatures(
    case_id: str, failure_text: str, verdict: str, sig: str, do_first_snippet: str
) -> None:
    # The LLM is called (it enriches the explanation) but its misleading
    # explanation must NOT change the verdict or the runbook action.
    llm = FakeQuesterLLM([MISLEADING_EXPLANATION])
    result = await analyze_failure(llm, AnalyzeFailureRequest(failure_text=failure_text))
    assert result.verdict == verdict
    assert result.deterministic is True
    assert result.matched_signature == sig
    assert do_first_snippet in result.what_to_do_first
    assert "rewrite the matching service" not in result.what_to_do_first
    assert result.failing_step
    assert len(llm.calls) == 1
    assert llm.calls[0][1] == 0


async def test_analyze_failure_no_signature_defaults_to_regression() -> None:
    llm = FakeQuesterLLM(
        [json.dumps({"likely_cause": "the seed data was stale", "what_to_do_first": "re-seed the test database and re-run"})]
    )
    result = await analyze_failure(
        llm, AnalyzeFailureRequest(failure_text="test_checkout exited with code 1, no other detail")
    )
    assert result.verdict == "regression"
    assert result.deterministic is False
    assert result.matched_signature is None
    assert result.likely_cause == "the seed data was stale"
    assert result.what_to_do_first == "re-seed the test database and re-run"



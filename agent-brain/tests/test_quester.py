def test_generate_tests_happy_path(monkeypatch) -> None:  # type: ignore[no-untyped-def]
    llm = FakeQuesterLLM([GOOD_PYTEST])
    _patch_auth_and_llm(monkeypatch, llm)
    resp = _client().post(
        "/quester/generate-tests",
        json={"target": "matching", "context": "GET /jobs lists jobs.", "known_endpoints": KNOWN},
        headers=AUTH,
    )
    assert resp.status_code == 200
    body = resp.json()
    assert len(body["tests"]) == 1
    assert body["tests"][0]["path"] == "tests/test_generated_jobs.py"
    assert "def test_list_jobs_returns_200" in body["tests"][0]["content"]
    assert body["warnings"] == []
    # The LLM was called exactly once, deterministically, with the endpoint list.
    assert len(llm.calls) == 1
    assert llm.calls[0][1] == 0
    assert "/jobs" in llm.calls[0][0][1]["content"]


